import { useCallback, useEffect, useRef, useState } from "react";
import { IconCheck as Check, IconCopy as Copy, IconDeviceMobile as Iphone, IconRefresh as Refresh } from "@tabler/icons-react";
import { Alert } from "@/components/ui/knowns/alert";
import { Badge } from "@/components/ui/knowns/badge";
import { Button } from "@/components/ui/knowns/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/knowns/card";
import { Empty } from "@/components/ui/knowns/empty";
import { Switch } from "@/components/ui/knowns/switch";
import { Spinner } from "@/components/ui/knowns/spinner";
import { ApiError, api } from "@/api";
import { QrCode } from "@/components/qr";
import { getLanguage, t, useLanguage } from "@/lib/i18n";
import type { DeviceInfo, Pairing } from "@/types";

function when(iso?: string | number): string {
  if (!iso) return t("never");
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? String(iso) : d.toLocaleString(getLanguage() === "vi" ? "vi-VN" : undefined);
}

export function DevicesPanel() {
  return (
    <div className="grid gap-4 lg:grid-cols-[360px_minmax(0,1fr)]">
      <PairingCard />
      <DeviceList />
    </div>
  );
}

function PairingCard() {
  useLanguage();
  const [pairing, setPairing] = useState<Pairing | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [copied, setCopied] = useState(false);
  const [useIp, setUseIp] = useState(false);
  const link = pairing ? (pairing.urlLocal && !useIp ? pairing.urlLocal : pairing.url) : "";

  const load = useCallback(async () => {
    try {
      setPairing(await api.getPairing());
      setError(null);
    } catch (e) {
      setError(e instanceof ApiError && e.status === 404 ? t("This agent does not support /api/pairing (404). Update the agent and reload.") : e instanceof Error ? e.message : String(e));
    }
  }, []);

  useEffect(() => {
    void load();
    // PIN is regenerated by the agent after failed attempts, so keep it fresh.
    const t = setInterval(() => void load(), 5000);
    return () => clearInterval(t);
  }, [load]);

  const regenerate = async () => {
    setBusy(true);
    try {
      setPairing(await api.regeneratePairing());
      setError(null);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  };

  const copy = async () => {
    if (!pairing) return;
    try {
      await navigator.clipboard.writeText(link);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      /* clipboard unavailable: the URL is selectable on screen */
    }
  };

  return (
    <Card>
      <CardHeader className="p-4 pb-0">
        <CardTitle className="text-sm">{t("Pair a phone")}</CardTitle>
      </CardHeader>
      <CardContent className="flex flex-col items-center gap-3 p-4">
        {error && <Alert tone="danger" className="w-full">{error}</Alert>}
        {!pairing && !error && <Spinner label={t("Loading")} />}
        {pairing && (
          <>
            <QrCode value={link} />
            <div className="text-center">
              <div className="text-xs text-muted-foreground">{t("PIN code")}</div>
              <div className="font-mono text-3xl font-semibold tracking-[0.3em] tabular-nums" aria-label={t("PIN {pin}", { pin: pairing.pin.split("").join(" ") })}>{pairing.pin}</div>
            </div>
            <code className="w-full break-all rounded-lg bg-muted px-2.5 py-1.5 text-center text-xs select-all">{link}</code>
            <p className="text-center text-xs text-muted-foreground">
              {t("Scan the QR code or open the link on a phone on the same Wi-Fi network.")}
            </p>
            {pairing.urlLocal && (
              <div className="flex w-full flex-col gap-1.5 rounded-lg border p-2.5">
                <label className="flex items-center justify-between gap-2 text-[13px]">
                  <span>{t("Use IP address")}</span>
                  <Switch checked={useIp} onCheckedChange={setUseIp} aria-label={t("Use IP address")} />
                </label>
                <p className="text-[11.5px] leading-snug text-muted-foreground">{t("Use the .local name so you do not have to pair again when the computer's IP changes.")}</p>
              </div>
            )}
            <div className="flex gap-2">
              <Button size="sm" variant="secondary" icon={copied ? <Check /> : <Copy />} onClick={copy}>{copied ? t("Copied") : t("Copy link")}</Button>
              <Button size="sm" variant="secondary" icon={<Refresh />} loading={busy} onClick={regenerate}>{t("New PIN")}</Button>
            </div>
          </>
        )}
      </CardContent>
    </Card>
  );
}

function DeviceList() {
  useLanguage();
  const [devices, setDevices] = useState<DeviceInfo[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [armed, setArmed] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [reloading, setReloading] = useState<string | null>(null);
  const armTimer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);

  const load = useCallback(async () => {
    try {
      setDevices(await api.getDevices());
      setError(null);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    }
  }, []);

  useEffect(() => {
    void load();
    const t = setInterval(() => void load(), 5000);
    return () => {
      clearInterval(t);
      clearTimeout(armTimer.current);
    };
  }, [load]);

  const reload = async (d?: DeviceInfo) => {
    setReloading(d?.id ?? "*");
    setNotice(null);
    try {
      const res = (await api.reloadDevices(d?.id)) as Record<string, unknown> | null;
      const n = [res?.sent, res?.count, res?.reloaded, res?.devices].find((v): v is number => typeof v === "number");
      const count = n ?? (d ? 1 : (devices ?? []).filter((x) => x.online).length);
      setNotice(t("Reload command sent to {count} devices", { count }));
      setError(null);
    } catch (e) {
      setError(t("Reload failed: {error}", { error: e instanceof Error ? e.message : String(e) }));
    } finally {
      setReloading(null);
    }
  };

  const revoke = async (d: DeviceInfo) => {
    if (armed !== d.id) {
      setArmed(d.id);
      clearTimeout(armTimer.current);
      armTimer.current = setTimeout(() => setArmed(null), 3000);
      return;
    }
    setArmed(null);
    try {
      await api.revokeDevice(d.id);
      await load();
    } catch (e) {
      setError(t("Revoke failed: {error}", { error: e instanceof Error ? e.message : String(e) }));
    }
  };

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between p-4 pb-0">
        <CardTitle className="text-sm">{t("Paired devices")}</CardTitle>
        <div className="flex gap-1.5">
          <Button size="xs" variant="secondary" icon={<Refresh />} loading={reloading === "*"} onClick={() => void reload()}>{t("Reload overlay")}</Button>
          <Button size="xs" variant="secondary" icon={<Refresh />} onClick={() => void load()}>{t("Refresh")}</Button>
        </div>
      </CardHeader>
      <CardContent className="flex flex-col gap-3 p-4">
        {error && <Alert tone="danger">{error}</Alert>}
        {notice && <Alert tone="success" onDismiss={() => setNotice(null)}>{notice}</Alert>}
        {!devices && !error && <Spinner label={t("Loading")} />}
        {devices && devices.length === 0 && (
          <Empty size="sm" icon={<Iphone />} title={t("No devices yet")} description={t("Scan the QR code or enter the PIN on a phone to pair.")} />
        )}
        {devices && devices.length > 0 && (
          <ul className="flex flex-col divide-y">
            {devices.map((d) => (
              <li key={d.id} className="flex items-center gap-3 py-2.5">
                <Iphone className="size-4 shrink-0 text-muted-foreground" />
                <div className="min-w-0 flex-1">
                  <div className="flex items-center gap-2">
                    <span className="truncate font-medium">{d.name || d.id}</span>
                    <Badge size="sm" tone={d.online ? "success" : "neutral"} dot>{d.online ? t("Online") : t("Offline")}</Badge>
                  </div>
                  <div className="text-xs text-muted-foreground">
                    {t("Paired: {when}", { when: when(d.createdAt) })} · {t("Last seen: {when}", { when: d.online ? t("now") : when(d.lastSeen) })}
                  </div>
                  {d.expiresAt !== undefined && <div className="text-xs text-muted-foreground">{t("Expires if unused: {when}", { when: when(d.expiresAt) })}</div>}
                </div>
                <Button size="sm" variant="secondary" loading={reloading === d.id} disabled={!d.online} onClick={() => void reload(d)}>{t("Reload")}</Button>
                <Button size="sm" variant="destructive" onClick={() => void revoke(d)}>{armed === d.id ? t("Confirm?") : t("Revoke")}</Button>
              </li>
            ))}
          </ul>
        )}
      </CardContent>
    </Card>
  );
}
